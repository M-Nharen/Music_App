/// The lyrics editor: a working copy, undo, what was touched, tap-along.
#[derive(Clone, Debug)]
pub struct LyricsEditor {
    pub doc: Lyrics,
    undo: Vec<Lyrics>,
    redo: Vec<Lyrics>,
    /// Line selected in the list.
    pub selected: usize,
    /// Tap-along: the next line a tap will time (None = not tapping).
    pub tapping: Option<usize>,
    /// Lines whose timing / words were changed (for per-line sources).
    pub timed: Vec<bool>,
    pub worded: Vec<bool>,
    pub dirty: bool,
    pub text_changed: bool,
    /// The line being typed into (one undo step per line, not per key).
    typing: Option<usize>,
    /// Song length (lines end with the song).
    pub duration: f64,
}

impl LyricsEditor {
    pub fn new(doc: Lyrics, duration: f64) -> LyricsEditor {
        let n = doc.lines.len();
        LyricsEditor {
            doc,
            undo: Vec::new(),
            redo: Vec::new(),
            selected: 0,
            tapping: None,
            timed: vec![false; n],
            worded: vec![false; n],
            dirty: false,
            text_changed: false,
            typing: None,
            duration,
        }
    }

    fn checkpoint(&mut self) {
        self.typing = None;
        self.undo.push(self.doc.clone());
        if self.undo.len() > 200 {
            self.undo.remove(0);
        }
        self.redo.clear();
        self.dirty = true;
    }

    pub fn can_undo(&self) -> bool {
        !self.undo.is_empty()
    }

    pub fn can_redo(&self) -> bool {
        !self.redo.is_empty()
    }

    pub fn undo(&mut self) {
        if let Some(d) = self.undo.pop() {
            self.redo.push(std::mem::replace(&mut self.doc, d));
            self.fit_flags();
        }
    }

    pub fn redo(&mut self) {
        if let Some(d) = self.redo.pop() {
            self.undo.push(std::mem::replace(&mut self.doc, d));
            self.fit_flags();
        }
    }

    fn fit_flags(&mut self) {
        let n = self.doc.lines.len();
        self.timed.resize(n, true);
        self.worded.resize(n, true);
        self.selected = self.selected.min(n.saturating_sub(1));
        if let Some(t) = self.tapping {
            self.tapping = Some(t.min(n));
        }
    }

    /// Give line `i` a new start; words move with it; the line before ends
    /// there if it used to end where this one started (or overlaps it).
    pub fn set_start(&mut self, i: usize, t: f64) {
        if i >= self.doc.lines.len() {
            return;
        }
        self.checkpoint();
        self.set_start_raw(i, t);
    }

    fn set_start_raw(&mut self, i: usize, t: f64) {
        let t = t.max(0.0);
        let lines = &mut self.doc.lines;
        let old = lines[i].start;
        let dt = old.map(|o| t - o);
        lines[i].start = Some(t);
        // Words: move with the line, or drop them if the line had no time.
        if let Some(words) = &mut lines[i].words {
            match dt {
                Some(dt) => {
                    for w in words.iter_mut() {
                        w.start += dt;
                        w.end += dt;
                    }
                }
                None => lines[i].words = None,
            }
        }
        // End: keep the length, but never past the next line.
        let next = lines[i + 1..].iter().find_map(|l| l.start.filter(|s| *s > t));
        let len = match (old, lines[i].end) {
            (Some(o), Some(e)) => (e - o).max(0.0),
            _ => f64::INFINITY,
        };
        let mut end = (t + len).min(next.unwrap_or(self.duration.max(t)));
        if !end.is_finite() {
            end = t + 4.0;
        }
        lines[i].end = Some(end.max(t));
        if let Some(words) = &mut lines[i].words
            && let Some(last) = words.last_mut()
        {
            last.end = last.end.min(end.max(last.start));
        }
        // The line before.
        if let Some(p) = (0..i).rev().find(|&p| lines[p].start.is_some()) {
            let pe = lines[p].end;
            let touches = match (pe, old) {
                (Some(e), Some(o)) => (e - o).abs() < 0.02,
                (None, _) | (_, None) => true,
            };
            if touches || pe.is_some_and(|e| e > t) {
                lines[p].end = Some(t.max(lines[p].start.unwrap_or(0.0)));
                if let Some(w) = &mut lines[p].words {
                    for w in w.iter_mut() {
                        w.end = w.end.min(t);
                        w.start = w.start.min(w.end);
                    }
                }
            }
        }
        self.timed[i] = true;
        self.resort(i);
    }

    /// Keep lines in time order after a change to line `i` (selection follows).
    fn resort(&mut self, i: usize) {
        let t = self.doc.lines[i].start;
        let mut j = i;
        while j > 0
            && let (Some(a), Some(b)) = (self.doc.lines[j - 1].start, t)
            && a > b
        {
            self.swap(j - 1, j);
            j -= 1;
        }
        while j + 1 < self.doc.lines.len()
            && let (Some(a), Some(b)) = (t, self.doc.lines[j + 1].start)
            && a > b
        {
            self.swap(j, j + 1);
            j += 1;
        }
        if self.selected == i {
            self.selected = j;
        }
    }

    fn swap(&mut self, a: usize, b: usize) {
        self.doc.lines.swap(a, b);
        self.timed.swap(a, b);
        self.worded.swap(a, b);
    }

    /// Move line `i` by `dt` seconds.
    pub fn nudge(&mut self, i: usize, dt: f64) {
        let Some(s) = self.doc.lines.get(i).and_then(|l| l.start) else {
            return;
        };
        self.set_start(i, s + dt);
    }

    /// Move every line (the whole song is early / late).
    pub fn shift_all(&mut self, dt: f64) {
        self.checkpoint();
        for (k, l) in self.doc.lines.iter_mut().enumerate() {
            if let Some(s) = &mut l.start {
                *s = (*s + dt).max(0.0);
                self.timed[k] = true;
            }
            if let Some(e) = &mut l.end {
                *e = (*e + dt).max(0.0);
            }
            if let Some(w) = &mut l.words {
                for w in w.iter_mut() {
                    w.start = (w.start + dt).max(0.0);
                    w.end = (w.end + dt).max(0.0);
                }
            }
        }
    }

    /// Change a line's text. Its romanised / English text are now stale
    /// (null until the analyzer runs again) and word timing is dropped.
    pub fn set_text(&mut self, i: usize, text: &str) {
        let Some(l) = self.doc.lines.get(i) else { return };
        if l.text == text {
            return;
        }
        if self.typing != Some(i) {
            self.checkpoint();
            self.typing = Some(i);
        }
        let l = &mut self.doc.lines[i];
        l.text = text.to_string();
        if l.is_latin() {
            let lang = l.language.clone().unwrap_or_default();
            l.romanized = (lang.ends_with("-Latn")).then(|| l.text.clone());
        } else {
            l.romanized = None;
        }
        l.translation = None;
        l.words = None;
        l.confidence = None;
        self.worded[i] = true;
        self.text_changed = true;
    }

    /// Add an empty line after `i` (or at the start), timed between its
    /// neighbours if they are timed.
    pub fn insert_after(&mut self, i: Option<usize>) -> usize {
        self.checkpoint();
        let at = i.map(|i| i + 1).unwrap_or(0).min(self.doc.lines.len());
        let mut l = Line::new("");
        l.language = self.doc.language.clone();
        let prev = at.checked_sub(1).and_then(|p| self.doc.lines.get(p));
        if let Some(p) = prev
            && let Some(s) = p.start
        {
            let e = p.end.unwrap_or(s + 2.0);
            l.start = Some(e);
            l.end = self.doc.lines.get(at).and_then(|n| n.start).or(Some(e + 2.0));
        }
        self.doc.lines.insert(at, l);
        self.timed.insert(at, true);
        self.worded.insert(at, true);
        self.text_changed = true;
        self.selected = at;
        at
    }

    pub fn remove(&mut self, i: usize) {
        if i >= self.doc.lines.len() {
            return;
        }
        self.checkpoint();
        self.doc.lines.remove(i);
        self.timed.remove(i);
        self.worded.remove(i);
        self.text_changed = true;
        self.fit_flags();
    }

    /// Remove every time (start tapping from scratch).
    pub fn clear_times(&mut self) {
        self.checkpoint();
        for (k, l) in self.doc.lines.iter_mut().enumerate() {
            l.start = None;
            l.end = None;
            l.start_beat = None;
            l.end_beat = None;
            l.words = None;
            self.timed[k] = true;
        }
    }

    // ---- tap-along

    pub fn start_tapping(&mut self, from: usize) {
        self.tapping = Some(from.min(self.doc.lines.len()));
    }

    /// A tap at song time `t`: the next line starts now. Returns the line timed.
    pub fn tap(&mut self, t: f64) -> Option<usize> {
        let mut i = self.tapping?;
        while i < self.doc.lines.len() && self.doc.lines[i].is_blank() {
            i += 1;
        }
        if i >= self.doc.lines.len() {
            self.tapping = None;
            return None;
        }
        self.checkpoint();
        // A tapped line ends at the next tap: drop the old end so it doesn't
        // cut the line short, and clear later lines' times that are now
        // before it (they'll be tapped next).
        self.doc.lines[i].end = None;
        self.set_start_raw(i, t);
        let i = self.selected_after_tap(i, t);
        self.tapping = Some(i + 1);
        self.selected = i;
        Some(i)
    }

    fn selected_after_tap(&mut self, i: usize, t: f64) -> usize {
        // set_start_raw may have re-sorted; find the line we timed.
        (0..self.doc.lines.len())
            .find(|&k| self.doc.lines[k].start == Some(t.max(0.0)) && self.timed[k])
            .unwrap_or(i)
    }

    /// Step back one tap.
    pub fn untap(&mut self) {
        if let Some(t) = self.tapping
            && t > 0
            && self.can_undo()
        {
            self.undo();
            self.tapping = Some(t - 1);
            self.selected = t - 1;
        }
    }

    pub fn stop_tapping(&mut self) {
        self.tapping = None;
    }

    /// Apply per-line sources and beats; the document to save.
    pub fn finish(&self, grid: &BeatGrid) -> Lyrics {
        let mut doc = self.doc.clone();
        let base_timing = doc.sources.timing.clone().or(doc.sources.words.clone());
        let base_words = doc.sources.words.clone();
        let all_timed = self.timed.iter().all(|x| *x) && !self.timed.is_empty();
        for (k, l) in doc.lines.iter_mut().enumerate() {
            let mut s = l.sources.take().unwrap_or_default();
            if self.timed.get(k).copied().unwrap_or(true) {
                s.timing = Some(Source::user("timing", base_timing.as_ref()));
            }
            if self.worded.get(k).copied().unwrap_or(true) {
                s.words = Some(Source::user("words", base_words.as_ref()));
            }
            l.sources = (!s.is_empty()).then_some(s);
        }
        // Retimed every line (tap-along from scratch): the song's timing is ours.
        if all_timed && doc.synced() {
            doc.sources.timing = Some(Source::user("timing", base_timing.as_ref()));
            doc.auto_generated.timing = false;
            for l in &mut doc.lines {
                if let Some(s) = &mut l.sources {
                    s.timing = None;
                }
                if l.sources.as_ref().is_some_and(|s| s.is_empty()) {
                    l.sources = None;
                }
                l.confidence = None;
            }
        }
        // Last line ends with the song.
        if let Some(last) = doc.lines.iter_mut().rev().find(|l| l.start.is_some())
            && last.end.is_none()
        {
            last.end = Some(self.duration.max(last.start.unwrap_or(0.0)));
        }
        // Lines with a start but no end end at the next line.
        let starts: Vec<Option<f64>> = doc.lines.iter().map(|l| l.start).collect();
        for (k, l) in doc.lines.iter_mut().enumerate() {
            if l.start.is_some() && l.end.is_none() {
                l.end = starts[k + 1..].iter().flatten().next().copied().or(Some(self.duration));
            }
        }
        doc.fix_beats(grid);
        doc.round_times();
        doc
    }
}

