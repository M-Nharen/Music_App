        e.set_text(0, "காலை தென்றல்");
        let l = &e.doc.lines[0];
        assert_eq!(l.romanized, None);
        assert_eq!(l.translation, None);
        assert!(l.words.is_none());
        assert!(e.text_changed);
        let d = e.finish(&grid());
        let s = d.lines[0].sources.as_ref().unwrap();
