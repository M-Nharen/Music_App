    #[test]
    fn retiming_moves_words_and_neighbours() {
        let mut e = LyricsEditor::new(doc(), 30.0);
        e.nudge(0, 0.5);
        let l0 = &e.doc.lines[0];
        assert_eq!(l0.start, Some(2.5));
        assert_eq!(l0.end, Some(6.0));
        assert_eq!(l0.timed_words().unwrap()[0].start, 2.5);
        assert_eq!(l0.timed_words().unwrap()[2].end, 5.0);
        // Line 2 starts where line 1 ended: moving it earlier moves that end.
        e.set_start(2, 9.5);
        assert_eq!(e.doc.lines[1].end, Some(9.5));
        assert_eq!(e.doc.lines[2].start, Some(9.5));
        // Can't run into the next line.
        e.set_start(1, 9.0);
        assert!(e.doc.lines[1].end.unwrap() <= 9.5 + 1e-9);
        e.undo();
        e.undo();
        e.undo();
        assert_eq!(e.doc, doc());
        e.redo();
        assert_eq!(e.doc.lines[0].start, Some(2.5));
    }

