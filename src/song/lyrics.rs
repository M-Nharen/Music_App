//! Lyrics (Part 10b): reading the analyzer's `lyrics.json` (see
//! `analyzer/SONG_FORMAT.md`), finding the line and word sung at a time,
//! choosing what to show (native script / romanised / English), the source
//! badge, and the lyrics editor's model (retiming, tap-along, text edits)
//! with saving.
//!
//! Saving: re-running the analyzer's lyrics step rewrites `lyrics.json`, so
//! an edit is written twice: into `lyrics.json` (so the app shows it at
//! once; edited lines get a per-line `"sources": {"timing" | "words": {"kind":
//! "user", …}}`) and as `lyrics/imported.lrc` + `imported.json` (with
//! `"editor": "qwertone"`), which the analyzer always picks first, so the
//! edit survives every later run. After a text edit the app runs
//! `qwertone-analyze lyrics <song> --force` to romanise / translate the new
//! words.
//!
//! Pure logic, no egui.

use super::BeatGrid;
use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use std::path::{Path, PathBuf};

/// Newest `format_version` of `lyrics.json` this app understands.
pub const FORMAT_VERSION: u32 = 1;
pub const FILE: &str = "lyrics.json";
pub const IMPORT_DIR: &str = "lyrics";
pub const IMPORT_LRC: &str = "imported.lrc";
pub const IMPORT_META: &str = "imported.json";
/// The `[re:]` tag / `editor` value marking our own exports.
pub const EDITOR_TAG: &str = "qwertone";

/// Where one layer (words, timing, translation, transliteration) came from.
#[derive(Clone, Debug, Default, Serialize, Deserialize, PartialEq)]
pub struct Source {
    #[serde(default)]
    pub kind: String,
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub url: Option<String>,
    #[serde(default)]
    pub file: Option<String>,
    #[serde(default)]
    pub fetched: Option<String>,
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl Source {
    /// A source for an edit made in the app.
    pub fn user(what: &str, based_on: Option<&Source>) -> Source {
        let mut extra = Map::new();
        extra.insert("edited".into(), Value::String(what.into()));
        if let Some(b) = based_on {
            extra.insert(
                "based_on".into(),
                serde_json::to_value(b).unwrap_or(Value::Null),
            );
        }
        Source {
            kind: "user".into(),
            name: "edited in Qwertone".into(),
            url: None,
            file: None,
            fetched: Some(now_iso()),
            extra,
        }
    }

    pub fn is_user(&self) -> bool {
        self.kind == "user"
    }

    pub fn auto_generated(&self) -> bool {
        self.extra
            .get("auto_generated")
            .and_then(|v| v.as_bool())
            .unwrap_or(false)
            || matches!(self.kind.as_str(), "whisper" | "aligner" | "translator")
    }

    pub fn machine_translation(&self) -> bool {
        self.extra
            .get("machine_translation")
            .and_then(|v| v.as_bool())
            .unwrap_or(self.kind == "translator")
    }

    /// What this edit was based on (for user edits).
    pub fn based_on(&self) -> Option<Source> {
        self.extra
            .get("based_on")
            .and_then(|v| serde_json::from_value(v.clone()).ok())
    }

    /// A string extra ("model", "id", …).
    pub fn get(&self, key: &str) -> Option<String> {
        match self.extra.get(key)? {
            Value::String(s) => Some(s.clone()),
            Value::Number(n) => Some(n.to_string()),
            _ => None,
        }
    }

    /// "26 Nov 2026" from `fetched`.
    pub fn fetched_date(&self) -> Option<String> {
        let f = self.fetched.as_deref()?;
        let (y, rest) = f.split_once('-')?;
        let (m, rest) = rest.split_once('-')?;
        let d = rest.get(..2)?;
        const M: [&str; 12] = [
            "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
        ];
        let mi: usize = m.parse().ok()?;
        Some(format!(
            "{} {} {y}",
            d.trim_start_matches('0'),
            M.get(mi.checked_sub(1)?)?
        ))
    }
}

#[derive(Clone, Debug, Default, Serialize, Deserialize, PartialEq)]
pub struct Sources {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub words: Option<Source>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub timing: Option<Source>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub translation: Option<Source>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub transliteration: Option<Source>,
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize, PartialEq)]
pub struct AutoGenerated {
    #[serde(default)]
    pub words: bool,
    #[serde(default)]
    pub timing: bool,
    #[serde(default)]
    pub translation: bool,
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize, PartialEq)]
pub struct Word {
    #[serde(default)]
    pub text: String,
    pub start: f64,
    pub end: f64,
    #[serde(default)]
    pub start_beat: Option<f64>,
    #[serde(default)]
    pub end_beat: Option<f64>,
    #[serde(default)]
    pub romanized: Option<String>,
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize, PartialEq)]
pub struct Line {
    #[serde(default)]
    pub start: Option<f64>,
    #[serde(default)]
    pub end: Option<f64>,
    #[serde(default)]
    pub start_beat: Option<f64>,
    #[serde(default)]
    pub end_beat: Option<f64>,
    #[serde(default)]
    pub text: String,
    #[serde(default)]
    pub language: Option<String>,
    #[serde(default)]
    pub romanized: Option<String>,
    #[serde(default)]
    pub translation: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub confidence: Option<f32>,
    #[serde(default)]
    pub words: Option<Vec<Word>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sources: Option<Sources>,
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl Line {
    pub fn new(text: &str) -> Line {
        Line {
            text: text.to_string(),
            ..Default::default()
        }
    }

    /// Written in Latin letters (Tanglish typed as such, English…).
    pub fn is_latin(&self) -> bool {
        is_latin(&self.text)
    }

    /// `ta-Latn` & co: the romanised text *is* the text.
    pub fn is_romanised_language(&self) -> bool {
        self.language.as_deref().is_some_and(|l| l.ends_with("-Latn"))
            || self.romanized.as_deref() == Some(self.text.as_str())
    }

    pub fn is_english(&self) -> bool {
        self.language.as_deref().is_some_and(|l| l == "en" || l.starts_with("en-"))
    }

    /// Words with timing, if any.
    pub fn timed_words(&self) -> Option<&[Word]> {
        self.words.as_deref().filter(|w| !w.is_empty())
    }

    pub fn is_blank(&self) -> bool {
        self.text.trim().is_empty()
    }
}

/// The whole `lyrics.json`.
#[derive(Clone, Debug, Default, Serialize, Deserialize, PartialEq)]
pub struct Lyrics {
    #[serde(default)]
    pub format: String,
    #[serde(default)]
    pub format_version: u32,
    #[serde(default)]
    pub status: String,
    #[serde(default)]
    pub language: Option<String>,
    #[serde(default)]
    pub languages: Vec<String>,
    #[serde(default)]
    pub language_source: Option<String>,
    #[serde(default)]
    pub has_word_timing: bool,
    #[serde(default)]
    pub auto_generated: AutoGenerated,
    #[serde(default)]
    pub offset: Option<f64>,
    #[serde(default)]
    pub sources: Sources,
    #[serde(default)]
    pub lines: Vec<Line>,
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

/// Which text layers to show.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Layers {
    pub native: bool,
    pub romanized: bool,
    pub english: bool,
}

/// One of the layers.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Layer {
    Native,
    Romanized,
    English,
}

/// Where we are in the lyrics at some time.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Position {
    /// The current line: the last one that has started (None before the first).
    pub line: Option<usize>,
    /// The current line is still being sung (false in a gap after it).
    pub active: bool,
    /// The next line to start.
    pub next: Option<usize>,
}

/// Word progress inside a line: (word index, 0..1 through that word).
pub type WordAt = Option<(usize, f32)>;

pub fn is_latin(s: &str) -> bool {
    s.chars().all(|c| c.is_ascii() || !c.is_alphabetic() || (c as u32) < 0x0370)
}

impl Lyrics {
    /// `lyrics.json` from a song folder. Ok(None) when there isn't one
    /// (the lyrics step never ran).
    pub fn load(dir: &Path) -> Result<Option<Lyrics>, String> {
        let p = dir.join(FILE);
        if !p.exists() {
            return Ok(None);
        }
        let text =
            std::fs::read_to_string(&p).map_err(|e| format!("couldn't read {FILE}: {e}"))?;
        Lyrics::from_json(&text).map(Some)
    }

    pub fn from_json(text: &str) -> Result<Lyrics, String> {
        let mut l: Lyrics =
            serde_json::from_str(text).map_err(|e| format!("{FILE} is broken: {e}"))?;
        if !l.format.is_empty() && l.format != "qwertone-lyrics" {
            return Err(format!("not Qwertone lyrics (format \"{}\")", l.format));
        }
        if l.format_version > FORMAT_VERSION {
            return Err(format!(
                "made by a newer analyzer (lyrics format {}); update Qwertone",
                l.format_version
            ));
        }
        l.normalise();
        Ok(l)
    }

    /// Lines in time order; broken times dropped; words in order.
    fn normalise(&mut self) {
        for l in &mut self.lines {
            if l.start.is_some_and(|t| !t.is_finite()) {
                l.start = None;
            }
            if l.end.is_some_and(|t| !t.is_finite()) {
                l.end = None;
            }
            if let (Some(s), Some(e)) = (l.start, l.end)
                && e < s
            {
                l.end = Some(s);
            }
            if let Some(w) = &mut l.words {
                w.retain(|w| w.start.is_finite() && w.end.is_finite());
                w.sort_by(|a, b| a.start.total_cmp(&b.start));
            }
        }
        if self.synced() {
            // Stable: equal times keep their order (repeated choruses).
            self.lines
                .sort_by(|a, b| a.start.unwrap_or(f64::MAX).total_cmp(&b.start.unwrap_or(f64::MAX)));
        }
    }

    /// Some line has a time (else it can only be shown as a list).
    pub fn synced(&self) -> bool {
        self.lines.iter().any(|l| l.start.is_some())
    }

    /// Every line has a time.
    pub fn fully_synced(&self) -> bool {
        !self.lines.is_empty() && self.lines.iter().all(|l| l.start.is_some() || l.is_blank())
    }

    pub fn has_words(&self) -> bool {
        self.lines.iter().any(|l| l.timed_words().is_some())
    }

    pub fn instrumental(&self) -> bool {
        self.status == "instrumental"
    }

    /// Which layers exist at all (the toggles to show).
    pub fn available(&self) -> Layers {
        let lines = || self.lines.iter().filter(|l| !l.is_blank());
        Layers {
            // Hide "native script" when every line is in Latin letters anyway.
            native: lines().any(|l| !l.is_latin() && !l.is_romanised_language()),
            romanized: lines().any(|l| {
                l.romanized
                    .as_deref()
                    .is_some_and(|r| !r.is_empty() && r != l.text)
            }),
            english: lines().any(|l| l.translation.as_deref().is_some_and(|t| !t.is_empty())),
        }
    }

    /// The texts to show for a line, main one first, with their layer.
    /// Never empty for a non-blank line: falls back to the line's text.
    pub fn texts<'a>(&self, line: &'a Line, want: Layers) -> Vec<(Layer, &'a str)> {
        let have = self.available();
        let want = Layers {
            native: want.native || !have.native,
            romanized: want.romanized && have.romanized,
            english: want.english && have.english,
        };
        let mut out: Vec<(Layer, &str)> = Vec::new();
        let push = |out: &mut Vec<(Layer, &'a str)>, layer, s: &'a str| {
            if !s.trim().is_empty() && !out.iter().any(|(_, x)| x.trim() == s.trim()) {
                out.push((layer, s));
            }
        };
        if want.native {
            push(&mut out, Layer::Native, &line.text);
        }
        if want.romanized {
            match line.romanized.as_deref() {
                Some(r) => push(&mut out, Layer::Romanized, r),
                // English / romanised lines are already in Latin letters.
                None if line.is_latin() => push(&mut out, Layer::Romanized, &line.text),
                None => {}
            }
        }
        if want.english {
            match line.translation.as_deref() {
                Some(t) => push(&mut out, Layer::English, t),
                None if line.is_english() || line.is_latin() && !line.is_romanised_language() => {
                    push(&mut out, Layer::English, &line.text)
                }
                None => {}
            }
        }
        if out.is_empty() {
            push(&mut out, Layer::Native, &line.text);
        }
        out
    }

    /// The line at song time `t` (seconds, Bluetooth offset already added).
    pub fn position(&self, t: f64) -> Position {
        // Lines are sorted by start; untimed ones sort last.
        let n = self
            .lines
            .partition_point(|l| l.start.is_some_and(|s| s <= t + 1e-9));
        let line = n.checked_sub(1);
        let next = (n..self.lines.len()).find(|&i| self.lines[i].start.is_some() && !self.lines[i].is_blank());
        let active = line.is_some_and(|i| {
            let l = &self.lines[i];
            !l.is_blank() && l.end.is_none_or(|e| t < e) && next.is_none_or(|j| self.lines[j].start.unwrap_or(f64::MAX) > t)
        });
        Position { line, active, next }
    }

    /// The word sung at `t` in line `i`, and how far through it.
    pub fn word_at(&self, i: usize, t: f64) -> WordAt {
        let words = self.lines.get(i)?.timed_words()?;
        let k = words.partition_point(|w| w.start <= t);
        let k = k.checked_sub(1)?;
        let w = &words[k];
        let frac = if w.end > w.start {
            ((t - w.start) / (w.end - w.start)).clamp(0.0, 1.0) as f32
        } else {
            1.0
        };
        Some((k, frac))
    }

    /// The source of `layer` for line `i` (its own override, else the song's).
    pub fn source(&self, i: Option<usize>, what: SourceOf) -> Option<&Source> {
        let line = i.and_then(|i| self.lines.get(i)).and_then(|l| l.sources.as_ref());
        line.and_then(|s| s.get(what)).or_else(|| self.sources.get(what))
    }

    /// Times to the millisecond (no 1.9000000000000001 in the file).
    pub fn round_times(&mut self) {
        let r = |x: &mut f64| *x = (*x * 1000.0).round() / 1000.0;
        let ro = |x: &mut Option<f64>| {
            if let Some(v) = x {
                *v = (*v * 1000.0).round() / 1000.0;
            }
        };
        for l in &mut self.lines {
            ro(&mut l.start);
            ro(&mut l.end);
            ro(&mut l.start_beat);
            ro(&mut l.end_beat);
            if let Some(w) = &mut l.words {
                for w in w {
                    r(&mut w.start);
                    r(&mut w.end);
                    ro(&mut w.start_beat);
                    ro(&mut w.end_beat);
                }
            }
        }
    }

    /// Recompute every beat position from the times.
    pub fn fix_beats(&mut self, grid: &BeatGrid) {
        for l in &mut self.lines {
            l.start_beat = l.start.map(|t| grid.beat_at(t));
            l.end_beat = l.end.map(|t| grid.beat_at(t));
            if let Some(w) = &mut l.words {
                for w in w {
                    w.start_beat = Some(grid.beat_at(w.start));
                    w.end_beat = Some(grid.beat_at(w.end));
                }
            }
        }
    }

    /// The lines as an (enhanced) LRC: `[mm:ss.xx]<mm:ss.xx>word …`, with a
    /// timestamped empty line where a line ends well before the next one
    /// (LRC's "instrumental gap"). Plain text if nothing is timed.
    pub fn to_lrc(&self, title: &str, artist: Option<&str>) -> String {
        let mut s = String::new();
        if !title.is_empty() {
            s.push_str(&format!("[ti:{}]\n", one_line(title)));
        }
        if let Some(a) = artist.filter(|a| !a.is_empty()) {
            s.push_str(&format!("[ar:{}]\n", one_line(a)));
        }
        if let Some(l) = self.language.as_deref().filter(|l| !l.is_empty()) {
            s.push_str(&format!("[la:{l}]\n"));
        }
        s.push_str(&format!("[re:{EDITOR_TAG}]\n"));
        let synced = self.fully_synced();
        for (i, l) in self.lines.iter().enumerate() {
            if l.is_blank() {
                continue;
            }
            let text = one_line(&l.text);
            match (synced, l.start) {
                (true, Some(t)) => {
                    s.push_str(&lrc_time(t, '[', ']'));
                    match l.timed_words() {
                        Some(words) => {
                            for w in words {
                                s.push_str(&lrc_time(w.start, '<', '>'));
                                s.push_str(&one_line(&w.text));
                                s.push(' ');
                            }
                            let end = words.last().map(|w| w.end).unwrap_or(t);
                            s.push_str(&lrc_time(end, '<', '>'));
                        }
                        None => s.push_str(&text),
                    }
                    s.push('\n');
                    let next = self.lines[i + 1..]
                        .iter()
                        .find(|x| !x.is_blank())
                        .and_then(|x| x.start);
                    if let (Some(e), Some(n)) = (l.end, next)
                        && n - e > 0.5
                    {
                        s.push_str(&lrc_time(e, '[', ']'));
                        s.push('\n');
                    }
                }
                _ => {
                    s.push_str(&text);
                    s.push('\n');
                }
            }
        }
        s
    }

    /// Save into a song folder: `lyrics.json` (keeps a one-time `.bak`) and
    /// `lyrics/imported.lrc` + `imported.json`, so the analyzer keeps the edit.
    pub fn save(&self, dir: &Path, title: &str, artist: Option<&str>) -> Result<(), String> {
        let mut doc = self.clone();
        doc.format = "qwertone-lyrics".into();
        if doc.format_version == 0 {
            doc.format_version = 1;
        }
        doc.has_word_timing = doc.has_words();
        doc.status = if doc.lines.iter().all(|l| l.is_blank()) {
            if doc.instrumental() { "instrumental".into() } else { "not_found".into() }
        } else if doc.synced() {
            "synced".into()
        } else {
            "plain".into()
        };
        let json = serde_json::to_string_pretty(&doc).map_err(|e| e.to_string())?;
        let path = dir.join(FILE);
        let bak = dir.join("lyrics.json.bak");
        if path.exists() && !bak.exists() {
            let _ = std::fs::copy(&path, &bak);
        }
        write_atomic(&path, json.as_bytes())?;

        let idir = dir.join(IMPORT_DIR);
        std::fs::create_dir_all(&idir).map_err(|e| format!("couldn't make {}: {e}", idir.display()))?;
        write_atomic(&idir.join(IMPORT_LRC), self.to_lrc(title, artist).as_bytes())?;
        let mut based = Map::new();
        for (k, s) in [("words", &self.sources.words), ("timing", &self.sources.timing)] {
            if let Some(s) = s {
                // Don't nest edits inside edits.
                let s = if s.is_user() { s.based_on().unwrap_or(s.clone()) } else { s.clone() };
                based.insert(k.into(), serde_json::to_value(s).unwrap_or(Value::Null));
            }
        }
        let meta = serde_json::json!({
            "original": "edited in Qwertone",
            "imported": now_iso(),
            "editor": EDITOR_TAG,
            "based_on": based,
        });
        write_atomic(
            &idir.join(IMPORT_META),
            serde_json::to_string_pretty(&meta).unwrap().as_bytes(),
        )?;
        Ok(())
    }

    /// Delete our saved edit (`lyrics/imported.*` written by the editor),
    /// so the next analyzer run looks the lyrics up again.
    pub fn forget_edit(dir: &Path) -> bool {
        let meta = dir.join(IMPORT_DIR).join(IMPORT_META);
        let ours = std::fs::read_to_string(&meta)
            .ok()
            .and_then(|t| serde_json::from_str::<Value>(&t).ok())
            .is_some_and(|v| v.get("editor").and_then(|e| e.as_str()) == Some(EDITOR_TAG));
        if ours {
            let _ = std::fs::remove_file(dir.join(IMPORT_DIR).join(IMPORT_LRC));
            let _ = std::fs::remove_file(meta);
        }
        ours
    }

    /// A new, empty document for typing / pasting lyrics in the app.
    pub fn from_text(text: &str, language: Option<&str>) -> Lyrics {
        let lines: Vec<Line> = text
            .lines()
            .map(|l| l.trim())
            .filter(|l| !l.is_empty())
            .map(|t| {
                let mut l = Line::new(t);
                l.language = language.map(|s| s.to_string());
                l
            })
            .collect();
        let src = Source::user("typed in", None);
        Lyrics {
            format: "qwertone-lyrics".into(),
            format_version: 1,
            status: if lines.is_empty() { "not_found".into() } else { "plain".into() },
            language: language.map(|s| s.to_string()),
            languages: language.map(|s| vec![s.to_string()]).unwrap_or_default(),
            sources: Sources {
                words: Some(src),
                ..Default::default()
            },
            lines,
            ..Default::default()
        }
    }
}

/// Which source of a line.
impl Sources {
    pub fn get(&self, what: SourceOf) -> Option<&Source> {
        match what {
            SourceOf::Words => self.words.as_ref(),
            SourceOf::Timing => self.timing.as_ref(),
            SourceOf::Translation => self.translation.as_ref(),
            SourceOf::Transliteration => self.transliteration.as_ref(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.words.is_none()
            && self.timing.is_none()
            && self.translation.is_none()
            && self.transliteration.is_none()
            && self.extra.is_empty()
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SourceOf {
    Words,
    Timing,
    Translation,
    Transliteration,
}

fn one_line(s: &str) -> String {
    s.replace(['\n', '\r'], " ").trim().to_string()
}

fn lrc_time(t: f64, open: char, close: char) -> String {
    let cs = (t.max(0.0) * 100.0).round() as u64;
    format!("{open}{:02}:{:02}.{:02}{close}", cs / 6000, cs / 100 % 60, cs % 100)
}

fn write_atomic(path: &Path, bytes: &[u8]) -> Result<(), String> {
    let tmp: PathBuf = path.with_extension("tmp-qwertone");
    std::fs::write(&tmp, bytes).map_err(|e| format!("couldn't write {}: {e}", path.display()))?;
    std::fs::rename(&tmp, path).map_err(|e| format!("couldn't write {}: {e}", path.display()))
}

/// Now as ISO 8601 UTC ("2026-11-26T10:59:27+00:00"), without a date crate.
pub fn now_iso() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    iso_from_unix(secs)
}

pub fn iso_from_unix(secs: i64) -> String {
    let days = secs.div_euclid(86_400);
    let rem = secs.rem_euclid(86_400);
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    format!(
        "{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}+00:00",
        rem / 3600,
        rem / 60 % 60,
        rem % 60
    )
}

