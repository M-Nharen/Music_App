    #[test]
    fn tap_along_times_plain_lyrics() {
        let mut e = LyricsEditor::new(Lyrics::from_text("one\ntwo\nthree", Some("ta-Latn")), 20.0);
        e.start_tapping(0);
        assert_eq!(e.tap(1.0), Some(0));
        assert_eq!(e.tap(3.0), Some(1));
        e.untap();
        assert_eq!(e.doc.lines[1].start, None);
        assert_eq!(e.tapping, Some(1));
        assert_eq!(e.tap(3.5), Some(1));
        assert_eq!(e.tap(6.0), Some(2));
        assert_eq!(e.tap(9.0), None);
        assert_eq!(e.tapping, None);
        let d = e.finish(&grid());
        assert!(d.fully_synced());
        assert_eq!(d.lines[0].end, Some(3.5));
        assert_eq!(d.lines[1].end, Some(6.0));
        assert_eq!(d.lines[2].end, Some(20.0));
        assert_eq!(d.lines[1].start_beat, Some(7.0));
        // Every line retimed: the song's timing source is the user.
        assert!(d.sources.timing.as_ref().unwrap().is_user());
        assert!(d.lines[0].sources.is_none());
    }

